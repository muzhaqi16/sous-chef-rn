#!/usr/bin/env node
// Find `<name>.generated.ts` files under `src/` that have no sibling
// `<name>.graphql` source. These are leftovers from deleted `.graphql`
// files — `near-operation-file` does not clean them up, and they break
// `tsc` when they import fragment types that no longer exist.
//
// Pass `--fix` to delete the orphans.

import { readFileSync, statSync, unlinkSync } from 'node:fs';
import { relative } from 'node:path';
import { filesUnder, REPO_ROOT } from './lib/tooling.mjs';

const SKIP = [/(^|\/)(node_modules|generated)(\/|$)/];
// Our own generators (`generate-env.js`, `generate-optimistic-fillers.mjs`)
// also write `.generated.ts` files, beside no `.graphql` of the same name. Each
// opens with this banner, so the file says who owns it and nothing is listed.
const OWN_GENERATOR_BANNER = /^\/\/ AUTO-GENERATED by scripts\//;
const writtenByOwnGenerator = file =>
  OWN_GENERATOR_BANNER.test(readFileSync(file, 'utf8').slice(0, 200));

const fix = process.argv.includes('--fix');
const orphans = filesUnder('src/**/*.generated.ts', { exclude: SKIP })
  .filter(f => !writtenByOwnGenerator(f))
  .filter(f => {
    const source = f.replace(/\.generated\.ts$/, '.graphql');
    try {
      statSync(source);
      return false;
    } catch {
      return true;
    }
  });

if (orphans.length === 0) {
  console.log('No orphaned .generated.ts files found.');
  process.exit(0);
}

for (const f of orphans) {
  const rel = relative(REPO_ROOT, f);
  if (fix) {
    unlinkSync(f);
    console.log(`deleted ${rel}`);
  } else {
    console.log(`orphan  ${rel}`);
  }
}

if (!fix) {
  console.log(
    `\n${orphans.length} orphan(s) found. Re-run with --fix to delete.`,
  );
  process.exit(1);
}
