#!/usr/bin/env node
/**
 * Writes the set of types whose rows carry a server `version: Int!`, for
 * `answerOrderingLink`: it keeps the device's copy of such a row when an
 * answer's copy is older. No schema ships in the bundle, so the list is
 * built here; part of `npm run codegen`.
 *
 * Usage:  node scripts/generate-versioned-types.mjs [--check]
 *   --check  fail when the file is stale, and write nothing.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import {
  buildSchema,
  getNullableType,
  isNonNullType,
  isObjectType,
} from 'graphql';
import { fromRoot } from './lib/tooling.mjs';

const CHECK = process.argv.includes('--check');
const SCHEMA_PATH = fromRoot('src', 'graphql', 'generated', 'schema.graphql');
const OUT = fromRoot(
  'src',
  'graphql',
  'generated',
  'versionedTypes.generated.ts',
);

const schema = buildSchema(readFileSync(SCHEMA_PATH, 'utf8'));
const versioned = Object.values(schema.getTypeMap())
  .filter(type => isObjectType(type) && !type.name.startsWith('__'))
  .filter(type => {
    const field = type.getFields().version;
    return (
      field !== undefined &&
      isNonNullType(field.type) &&
      String(getNullableType(field.type)) === 'Int'
    );
  })
  .map(type => type.name)
  .sort();

const next = `// Generated by scripts/generate-versioned-types.mjs. Do not edit.
/** Types whose rows carry a server \`version: Int!\`, raised on every write. */
export const VERSIONED_TYPES: ReadonlySet<string> = new Set([
${versioned.map(name => `  '${name}',`).join('\n')}
]);
`;

const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
if (CHECK) {
  if (current !== next) {
    console.error(
      '✗ versionedTypes.generated.ts is out of date: run npm run codegen',
    );
    process.exit(1);
  }
  console.log(`✓ ${versioned.length} versioned types up to date`);
} else if (current !== next) {
  writeFileSync(OUT, next);
  console.log(`✓ wrote ${versioned.length} versioned types`);
} else {
  console.log(`✓ ${versioned.length} versioned types unchanged`);
}
